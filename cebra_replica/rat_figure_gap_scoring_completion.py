"""Finish Figure 2d metric coverage by reusing V2 scores and adding only gaps.

Verified V2 rows are copied unchanged. This script scores only openTSNE fits
not already present in that table; it does not fit any neural/baseline model.
"""
from __future__ import annotations

import csv
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "cebra_replica"))
import rat_manifold_scoring as scorer  # noqa: E402

OUT = ROOT / "results" / "rat_figure_gap_closure_v1" / "figure2d_metrics"
SOURCE = ROOT / "results" / "rat_manifold_decoding_v2_umap_complete"
SOURCE_LONG = SOURCE / "RAT_METHOD_DECODING_LONG.csv"
SOURCE_PROV = SOURCE / "RAT_METHOD_DECODING_PROVENANCE.json"


def main() -> None:
    if OUT.exists() and any(OUT.iterdir()):
        raise RuntimeError(f"Refusing to overwrite non-empty output directory: {OUT}")
    prov = json.loads(SOURCE_PROV.read_text(encoding="utf-8"))
    current_scorer_hash = scorer.sha256_file(Path(scorer.__file__))
    if prov["scorer_sha256"] != current_scorer_hash:
        raise RuntimeError("V2 metrics were not generated by the current unchanged scorer")
    with SOURCE_LONG.open(newline="", encoding="utf-8-sig") as stream:
        reused_rows = list(csv.DictReader(stream))
    if not reused_rows:
        raise RuntimeError("V2 score table is empty")

    # Verify every reused row's parent manifest and corresponding embedding hash.
    verified_manifests = {}
    for row in reused_rows:
        path = ROOT / row["parent_result_path"]
        expected = row["parent_result_sha256"]
        if scorer.sha256_file(path) != expected:
            raise RuntimeError(f"V2 parent manifest hash mismatch: {path}")
        manifest = verified_manifests.setdefault(path, json.loads(path.read_text(encoding="utf-8")))
        split = row["split"]
        entry = manifest["embeddings"][split]
        expected_embedding = entry["sha256"] if manifest.get("method") else entry["embedding_sha256"]
        if row["parent_embedding_sha256"] != expected_embedding:
            raise RuntimeError(f"V2 row's embedding provenance mismatch: {path}/{split}")

    existing_paths = {row["parent_result_path"] for row in reused_rows}
    new_rows = []
    new_manifests = []
    for manifest_path in sorted(scorer.BASELINE_ROOT.rglob("result.json")):
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest.get("method", "").lower() != "opentsne":
            continue
        if manifest.get("status") not in ("complete", "complete_embeddings_only"):
            continue
        rel = manifest_path.relative_to(ROOT).as_posix()
        if rel in existing_paths:
            continue
        new_rows.extend(scorer.score_fit(manifest_path, "OPENTSNE", None, True,
                                         scorer.support_for(manifest["rat"], int(manifest["fold"]))))
        new_manifests.append({"path": rel, "sha256": scorer.sha256_file(manifest_path)})

    merged_rows = reused_rows + new_rows
    unique_fits = {row["parent_result_path"] for row in merged_rows}
    if len(new_manifests) != 119 or len(new_rows) != 238:
        raise RuntimeError(f"Unexpected missing openTSNE coverage: {len(new_manifests)} fits, {len(new_rows)} rows")
    if len(unique_fits) != 492 or len(merged_rows) != 984:
        raise RuntimeError(f"Unexpected final score coverage: {len(unique_fits)} fits, {len(merged_rows)} rows")
    split_counts = {}
    for row in merged_rows:
        key = (row["parent_result_path"], row["split"])
        split_counts[key] = split_counts.get(key, 0) + 1
    if any(v != 1 for v in split_counts.values()) or len(split_counts) != 984:
        raise RuntimeError("Duplicate/missing method × fit × split score rows")

    run_rows, summary_rows = scorer.aggregate(merged_rows)
    OUT.mkdir(parents=True, exist_ok=True)
    scorer.atomic_csv(OUT / "RAT_METHOD_DECODING_LONG.csv", merged_rows, list(merged_rows[0]))
    scorer.atomic_csv(OUT / "RAT_METHOD_DECODING_SEED_LEVEL.csv", run_rows, list(run_rows[0]))
    scorer.atomic_csv(OUT / "RAT_METHOD_DECODING_SUMMARY.csv", summary_rows, list(summary_rows[0]))
    method_counts = {}
    for row in merged_rows:
        key = f"{row['method']} | {row['condition']}"
        method_counts[key] = method_counts.get(key, 0) + 1
    final_prov = {"created_utc": datetime.now(timezone.utc).isoformat(),
        "operation": "downstream metric coverage closure; no encoder fitting",
        "output_dir": str(OUT), "source_v2_directory": str(SOURCE),
        "source_v2_long_sha256": scorer.sha256_file(SOURCE_LONG),
        "source_v2_provenance_sha256": scorer.sha256_file(SOURCE_PROV),
        "source_v2_scorer_sha256_verified_equal_to_current": current_scorer_hash,
        "reused_rows_unchanged": len(reused_rows), "new_openTSNE_rows": len(new_rows),
        "new_openTSNE_fit_manifests": new_manifests,
        "completed_unique_fits": len(unique_fits), "long_rows": len(merged_rows),
        "method_condition_row_counts": method_counts,
        "decoder": {"type": "scikit-learn k-nearest-neighbors", "k": scorer.K,
                    "distance": "cosine", "fit_split": "train only"},
        "scored_splits": ["valid", "test"],
        "support_policy": "exact support from existing frozen splitter; within-trial 250 ms centers; boundary rows excluded",
        "test_use": "held-out evaluation only; no selection or tuning",
        "script_sha256": scorer.sha256_file(Path(__file__))}
    scorer.atomic_json(OUT / "RAT_METHOD_DECODING_PROVENANCE.json", final_prov)
    print(json.dumps({"reused_rows": len(reused_rows), "new_openTSNE_rows": len(new_rows),
                      "unique_fits": len(unique_fits), "long_rows": len(merged_rows),
                      "method_counts": method_counts}, indent=2), flush=True)


if __name__ == "__main__":
    main()
